use crate::error::{Result, VwlError};
use std::path::{Path, PathBuf};
use std::process::Command;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GitRepoInfo {
    pub root: PathBuf,
    pub head_sha: String,
    pub tree_sha: String,
    pub canonical_base: Option<String>,
}

pub struct GitInspector;

impl GitInspector {
    pub fn find_repo_root(start_dir: &Path) -> Result<PathBuf> {
        let output = Command::new("git")
            .arg("rev-parse")
            .arg("--show-toplevel")
            .current_dir(start_dir)
            .output()
            .map_err(|e| VwlError::GitCommandFailed(e.to_string()))?;

        if !output.status.success() {
            return Err(VwlError::NotAGitRepository(
                start_dir.to_string_lossy().to_string(),
            ));
        }

        let root_str = String::from_utf8_lossy(&output.stdout).trim().to_string();
        Ok(PathBuf::from(root_str))
    }

    pub fn inspect(start_dir: &Path) -> Result<GitRepoInfo> {
        let root = Self::find_repo_root(start_dir)?;

        // HEAD commit SHA
        let head_output = Command::new("git")
            .arg("rev-parse")
            .arg("HEAD")
            .current_dir(&root)
            .output()
            .map_err(|e| VwlError::GitCommandFailed(e.to_string()))?;

        let head_sha = if head_output.status.success() {
            String::from_utf8_lossy(&head_output.stdout)
                .trim()
                .to_string()
        } else {
            "unborn".to_string()
        };

        // Tree SHA of HEAD
        let tree_sha = if head_sha != "unborn" {
            let tree_output = Command::new("git")
                .arg("rev-parse")
                .arg("HEAD^{tree}")
                .current_dir(&root)
                .output()
                .map_err(|e| VwlError::GitCommandFailed(e.to_string()))?;
            if tree_output.status.success() {
                String::from_utf8_lossy(&tree_output.stdout)
                    .trim()
                    .to_string()
            } else {
                "empty".to_string()
            }
        } else {
            "empty".to_string()
        };

        // Read canonical base if stored in .vwl/canonical_base
        let canonical_file = root.join(".vwl").join("canonical_base");
        let canonical_base = if canonical_file.exists() {
            std::fs::read_to_string(canonical_file)
                .ok()
                .map(|s| s.trim().to_string())
        } else {
            None
        };

        Ok(GitRepoInfo {
            root,
            head_sha,
            tree_sha,
            canonical_base,
        })
    }

    pub fn set_canonical_base(repo_root: &Path, commit_sha: &str) -> Result<()> {
        let vwl_dir = repo_root.join(".vwl");
        if !vwl_dir.exists() {
            std::fs::create_dir_all(&vwl_dir)?;
        }
        std::fs::write(vwl_dir.join("canonical_base"), commit_sha)?;
        Ok(())
    }

    pub fn install_precommit_hook(repo_root: &Path) -> Result<PathBuf> {
        let hooks_dir = repo_root.join(".git").join("hooks");
        std::fs::create_dir_all(&hooks_dir)?;
        let hook_path = hooks_dir.join("pre-commit");
        let script = r#"#!/bin/sh
# VWL Pre-Commit Verification Gate Hook
# Generated by 'vwl init', 'vwl bootstrap', or 'vwl hook install'
echo "[VWL Hook] 🔍 Running pre-commit validator gates..."
if command -v vwl >/dev/null 2>&1; then
  vwl verify precommit
elif [ -x "$HOME/.cargo/bin/vwl" ]; then
  "$HOME/.cargo/bin/vwl" verify precommit
elif [ -x "./target/debug/vwl" ]; then
  ./target/debug/vwl verify precommit
elif [ -x "./target/release/vwl" ]; then
  ./target/release/vwl verify precommit
elif [ -f "./node_modules/.bin/vwl" ]; then
  ./node_modules/.bin/vwl verify precommit
elif command -v npx >/dev/null 2>&1 && npm list @horia-ai/vwl >/dev/null 2>&1; then
  npx @horia-ai/vwl verify precommit
else
  echo "[VWL Hook] ⚠️ Native 'vwl' binary not in PATH; skipping hook until vwl is compiled or installed."
  exit 0
fi
EXIT_CODE=$?
if [ $EXIT_CODE -ne 0 ]; then
  echo "[VWL Hook] ❌ Pre-commit validator gates failed (exit code $EXIT_CODE). Commit aborted."
  exit $EXIT_CODE
fi
echo "[VWL Hook] ✅ All pre-commit validator gates passed."
exit 0
"#;
        std::fs::write(&hook_path, script)?;

        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mut perms = std::fs::metadata(&hook_path)?.permissions();
            perms.set_mode(0o755);
            std::fs::set_permissions(&hook_path, perms)?;
        }

        Ok(hook_path)
    }

    pub fn uninstall_precommit_hook(repo_root: &Path) -> Result<bool> {
        let hook_path = repo_root.join(".git").join("hooks").join("pre-commit");
        if hook_path.exists() {
            std::fs::remove_file(hook_path)?;
            Ok(true)
        } else {
            Ok(false)
        }
    }

    pub fn is_precommit_hook_installed(repo_root: &Path) -> bool {
        let hook_path = repo_root.join(".git").join("hooks").join("pre-commit");
        if let Ok(content) = std::fs::read_to_string(&hook_path) {
            content.contains("vwl verify precommit")
        } else {
            false
        }
    }
}
